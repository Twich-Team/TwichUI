-- World map exploration's data (map/Data.lua, made by tools/mapdata/build.py from the game clients): its shape, and that
-- every place and map in it is usable by map/ (nothing here can say the game draws them; that is for the game).
dofile(TESTS .. "harness.lua")
local env = { TwichUI = {} }
setmetatable(env, { __index = _G })
local chunk = assert(loadfile(ROOT .. "map/Data.lua"))
setfenv(chunk, env)
chunk("!!!TwichUI", {})
local D = env.TwichUI.MapExploreData
assert(type(D) == "table" and type(D.build) == "string" and D.build:match("^%d+%.%d+%.%d+%.%d+$"), "a Forever build named")

local function FileID(v) return type(v) == "number" and v % 1 == 0 and v > 0 end

-- the minimap: every continent's tiles, each inside the 64 x 64 grid, each tile once
local tiles = 0
for cont, s in pairs(D.minimap) do
  assert(cont == 0 or cont == 1 or cont == 2991, "a Forever continent: " .. tostring(cont))
  local seen = {}
  for col, row, fd in s:gmatch("(%d+),(%d+),(%d+)") do
    col, row, fd = tonumber(col), tonumber(row), tonumber(fd)
    assert(col >= 0 and col <= 63 and row >= 0 and row <= 63 and FileID(fd), "a tile in the grid")
    assert(not seen[col * 64 + row], "each tile once")
    seen[col * 64 + row] = true
    tiles = tiles + 1
  end
  assert(not s:gsub("%d+,%d+,%d+", ""):find("%S"), "nothing else in the list")
end
assert(tiles > 1000, "both continents' minimaps: " .. tiles)

-- explored-area pieces: each "w:h:x:y:files" inside the 1002 x 668 art, with one file per 256-pixel tile
local pieces = 0
for art, str in pairs(D.reveal) do
  assert(type(art) == "number" and type(str) == "string", "a zone art's pieces")
  for w, h, x, y, files in str:gmatch("(%d+):(%d+):(%d+):(%d+):([%d,]+)") do
    w, h, x, y = tonumber(w), tonumber(h), tonumber(x), tonumber(y)
    assert(w > 0 and h > 0 and x >= 0 and y >= 0 and x + w <= 1024 and y + h <= 768, "a piece within its art")
    local n = 0
    for _ in files:gmatch("%d+") do n = n + 1 end
    assert(n == math.ceil(w / 256) * math.ceil(h / 256), "one file per tile")
    pieces = pieces + 1
  end
end
assert(pieces > 800, "the zones' pieces: " .. pieces)

-- caves: a picture of 12 tiles over a rectangle the picture's shape (1002 x 668 is 3:2), on Eastern Kingdoms or Kalimdor
local ids, groups = {}, {}
for _, c in ipairs(D.caves) do
  local id, name, cont, x0, y0, x1, y1, t = c[1], c[2], c[3], c[4], c[5], c[6], c[7], c[8]
  assert(FileID(id) and not ids[id], "a cave map once")
  ids[id] = true
  assert(type(name) == "string" and #name > 0 and (cont == 0 or cont == 1), "named, on a continent")
  assert(x1 > x0 and y1 > y0, "a rectangle")
  local aspect = (y1 - y0) / (x1 - x0)
  assert(math.abs(aspect - 1.5) < 0.02, ("drawn 3:2 (%s: %.3f)"):format(name, aspect))
  assert(#t == 12, "twelve tiles")
  for _, fd in ipairs(t) do assert(FileID(fd), "a file ID") end
  if c[9] then
    groups[c[9]] = (groups[c[9]] or 0) + 1
    assert(type(c[10]) == "number" and type(c[11]) == "string", "a floor has its order and name")
  end
end
for g, n in pairs(groups) do assert(n >= 2, "a floor group has floors: " .. g) end
assert(#D.caves >= 10, "caves: " .. #D.caves)

-- dungeons: an entrance, floors, or both; each floor 12 tiles
local entrances, maps = 0, 0
for inst, d in pairs(D.dungeons) do
  assert(type(inst) == "number" and type(d.name) == "string" and type(d.raid) == "boolean", "a dungeon")
  assert(d.entrance or #d.floors > 0, d.name .. " has something to show")
  if d.entrance then
    entrances = entrances + 1
    assert((d.entrance[1] == 0 or d.entrance[1] == 1) and type(d.entrance[2]) == "number" and type(d.entrance[3]) == "number", "an entrance")
  end
  if #d.floors > 0 then maps = maps + 1 end
  for _, fl in ipairs(d.floors) do
    assert(FileID(fl[1]) and type(fl[2]) == "string" and #fl[3] == 12, d.name .. ": a floor")
  end
end
assert(entrances >= 5 and maps >= 5, "dungeons: " .. entrances .. " entrances, " .. maps .. " maps")

-- travel: every leg between two docks the data has, boat or zeppelin
local legs = 0
for _, leg in ipairs(D.travel) do
  assert((leg[1] == "boat" or leg[1] == "zeppelin") and D.docks[leg[2]] and D.docks[leg[3]] and leg[2] ~= leg[3], "a leg between docks")
  legs = legs + 1
end
for id, d in pairs(D.docks) do
  assert(type(d[1]) == "string" and type(d[2]) == "string" and (d[3] == 0 or d[3] == 1 or d[3] == 2991), "a dock")
  local used = false
  for _, leg in ipairs(D.travel) do if leg[2] == id or leg[3] == id then used = true end end
  assert(used, "every dock is on a route")
end
assert(legs >= 20, "routes: " .. legs)

-- the generator is the data's only source: no hand edits (its header says so) and no art paths
local f = assert(io.open(ROOT .. "map/Data.lua"))
local src = f:read("*a")
f:close()
assert(src:find("Generated by tools/mapdata/build.py", 1, true), "says where it comes from")
assert(not src:find("Interface\\", 1, true) and not src:find("%.blp") and not src:find("%.tga"), "no texture paths: only the game's file IDs")
print("MAP DATA PASSED")

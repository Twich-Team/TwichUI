dofile(TESTS .. "settings_mock.lua")
local c, S = SettingsClient({ beforeInit = function(c)
  -- Describe the optional Workshop settings without loading or opening its window.
  c.TwichUI.WorkshopLauncher = { Loaded = function() return false end }
end })
local K, D = S.K, c.TwichUI.SettingsDesign
assert(D and D.pages)
for key, groups in pairs(D.tasks) do
  local page = assert(K.pages[key], "task page is registered: " .. key)
  local headers = {}
  for _, row in ipairs(page.rows) do if row.kind == "header" then headers[row:GetName()] = true end end
  for _, group in ipairs(groups) do
    for i = 2, #group do
      -- RestedXP describes additional sections only when that optional addon is installed.
      assert(headers[group[i]] or key == "restedxp", "task references a real section: " .. key .. " / " .. group[i])
    end
  end
end
for _, definition in ipairs(K.definitions) do
  assert(D.pages[definition.key], "every registered page needs a purposeful presentation review: " .. definition.key)
end
assert(#S.pages == 58, "all conditional pages are included for this synthetic Mage")
assert(not c.LOADED.TwichUI_Workshop, "describing Home and Workshop never loads the Workshop")
assert(not c.TwichUIDB.ui.settingsWindow, "describing settings never writes a window size")
local privacy = D.SectionSummary(K.pages.guildLocations, { GetName = function() return "Your location" end }, "On by default.")
assert(privacy:find("sends your current position", 1, true) and privacy:find("Invisible", 1, true), "concise privacy help retains the sending behavior")

-- Explicit audit export, like the existing contract test's opt-in fixture generation. Normal tests write nothing.
if os.getenv("TWICHUI_SETTINGS_INVENTORY") == "1" then
  local file = assert(io.open(REPO .. "docs/settings-modernization-inventory.md", "w"))
  file:write("# Settings inventory\n\nGenerated by `tests/test_settings_design.lua` with `TWICHUI_SETTINGS_INVENTORY=1`. Synthetic Mage; optional Workshop launcher present.\n\n")
  file:write("This is the actual registered catalog, including subsections, setting IDs, control types, defaults and dependency parents. Feature setters remain authoritative; the settings contract tests their saved destinations and reset behavior. Hosted editors retain their own models and validation. See [the workflow review](settings-second-pass.md) and [rollout tracker](settings-modernization.md) for usability work and verification.\n\n")
  local function Plain(value)
    return tostring(value or ""):gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""):gsub("|", " / "):gsub("\n", " ")
  end
  for _, page in ipairs(K.NavOrder()) do
    file:write("## ", page.name, " (`", page.key, "`)\n\n", Plain(page.def.description), "\n\n")
    file:write("Navigation: ", page.parent and K.pages[page.parent].name or "sidebar", "; ", page.group,
      ". ", page.def.host and "Contains a hosted editor. " or "", "Presentation: ", D.Intro(page), "\n\n")
    if #page.rows > 0 then
      file:write("| ID | Control / task | Kind | Saved variable / default | Dependency |\n|---|---|---|---|---|\n")
      for _, row in ipairs(page.rows) do
        local setting = row.data and row.data.setting
        local saved = setting and (setting.variable .. " = " .. tostring(setting.default)) or "—"
        file:write("| ", row.id, " | ", Plain(row:GetName()), " | ", row.kind, " | ", Plain(saved), " | ",
          row.parent and Plain(row.parent:GetName()) or "—", " |\n")
      end
    else file:write("Controls are provided by the hosted editor; source and tests are listed in the tracker.\n") end
    file:write("\n")
  end
  file:close()
end

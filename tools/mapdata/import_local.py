import argparse
import hashlib
import math
from pathlib import Path
import re

SHA256 = "5ff93b49dfde49e5916ab34d2a197cb2a3813aa0864c37a2a88495cc2dd52dc5"
RECORD = re.compile(r'\s*(?:\[(\d+)\] = )?\{ ([^{}]+), \{ ([^{}]*) \} \},\s*(?:-- .*)?')
NUMBER = re.compile(r'-?\d+(?:\.\d+)?')


def numbers(text):
    parts = [p.strip() for p in text.split(',')]
    if not all(NUMBER.fullmatch(p) for p in parts):
        raise ValueError('not a numeric record')
    return [float(p) for p in parts]


def convert(source):
    raw = source.rstrip() + '\n'
    if hashlib.sha256(raw.encode()).hexdigest() != SHA256:
        raise ValueError('source differs from the reviewed pinned upstream file')
    caves, cities = [], []
    for line in raw.splitlines():
        m = RECORD.fullmatch(line)
        if not m:
            continue
        box = numbers(m[2])
        if len(box) != 5 or box[0] not in (0, 1) or box[1] >= box[3] or box[2] >= box[4]:
            raise ValueError('invalid world rectangle')
        # Three picture references in two areas use an edited Blizzard texture (MapCaveMend).
        # Keep their original numeric neighbours, omit the edited picture entirely.
        tokens = [p.strip() for p in m[3].split(',')]
        if len(tokens) % 7:
            raise ValueError('incomplete WMO picture')
        pictures = []
        for i in range(0, len(tokens), 7):
            pic = tokens[i:i + 7]
            if pic[0] == 'M .. "215101"':
                continue
            vals = numbers(','.join(pic))
            if not all(math.isfinite(v) for v in vals) or vals[0] <= 0 or vals[0] % 1 or vals[3] <= 0:
                raise ValueError('invalid WMO picture')
            pictures.extend(pic)
        record = '{ ' + m[2] + ', { ' + ', '.join(pictures) + ' } }'
        if m[1]:
            if int(m[1]) not in (1455, 1458):
                raise ValueError('unexpected underground city')
            cities.append('    [' + m[1] + '] = ' + record + ',')
        else:
            caves.append('    ' + record + ',')
    if len(caves) != 248 or len(cities) != 2:
        raise ValueError('incomplete upstream data')
    return ('-- Generated by tools/mapdata/import_local.py; numeric client references only.\n'
            '-- OpenMap contributors (MIT): LICENSES/OpenMap.txt. No artwork is bundled.\n'
            '-- Source 6c2299f6e1f9bdce1bbd92145f84a05b0c6c05a7; Forever 1.60.1.70245.\n'
            'local D = { build = "1.60.1.70245" }\nTwichUI.MapExploreLocalData = D\n'
            'D.caves = {\n' + '\n'.join(caves) + '\n}\nD.cities = {\n' + '\n'.join(cities) + '\n}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[2] / '!!!TwichUI/map/LocalData.lua')
    args = parser.parse_args()
    args.output.write_text(convert(args.source.read_text()), encoding='utf-8')

#!/usr/bin/env python3
"""Build TwichUI-owned mathematical map masks; no game artwork is an input.

The right-soft mask keeps the existing 4% left/top/bottom smoothstep feather,
and widens only the right feather to 20/256 of the canvas. Pixel-centre signed
edge distances define every byte. This original formula contains no traced or
copied Blizzard/OpenMap pixels. Standard-library only; deterministic output.

    python3 tools/make_map_feather_art.py
    python3 tools/make_map_feather_art.py --check
"""
import argparse
import math
from pathlib import Path
import struct

SIZE = 256
EDGE = .04
RIGHT_SOFT = 20 / 256
OUTPUT = Path(__file__).resolve().parents[1] / "!!!TwichUI/media/textures/map-feather-right-soft.tga"


def make_tga(right=RIGHT_SOFT):
    """Return uncompressed 32-bit BGRA, bottom-left origin, 8 alpha bits.

    Passing right=EDGE reconstructs map-feather-thin.tga for compatibility
    verification. The other three edge distances always retain EDGE.
    """
    if isinstance(right, bool) or not isinstance(right, (int, float)) or not math.isfinite(right) or not 0 < right <= 1:
        raise ValueError("right feather must be finite and within (0, 1]")
    header = struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, SIZE, SIZE, 32, 8)
    pixels = bytearray()
    for y in range(SIZE):
        v = (y + .5) / SIZE
        for x in range(SIZE):
            u = (x + .5) / SIZE
            t = max(0, min(1, u / EDGE, (1 - u) / right, v / EDGE, (1 - v) / EDGE))
            pixels.extend((255, 255, 255, round(255 * t * t * (3 - 2 * t))))
    return header + pixels


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="verify exact generated bytes without writing anything")
    args = parser.parse_args(argv)
    expected = make_tga()
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != expected:
            print("Map feather differs or is absent; regenerate with tools/make_map_feather_art.py")
            return 1
        print("Map feather verified: deterministic 256x256 BGRA, mathematical source only")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(expected)
    print("Built mathematical map feather: " + str(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

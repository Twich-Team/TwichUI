-- Handler-level support workflow with real simulator widgets. No game assets,
-- physical keyboard/clipboard, native map visuals or live failures are claimed.
local R = TwichUI
A_Admin.SetManualClock(GetTime())
Lab.Solo()
local DX, MC, W
Lab.Step("open map support", function()
    R.DiagnosticsLauncher.OpenMap()
    DX = R.DiagnosticsKit; MC = DX.MapCapture; W = DX.MapWindow
    Lab.Check("construct", "support window visible", true, W.frame:IsShown())
    Lab.Check("state", "no recorder before start", nil, R.MapTrace)
    W.note:SetText("Synthetic map support workflow; no native failure.")
    W.capture:Click()
    Lab.Check("interact", "snapshot captured", true, MC.Current() ~= nil)
    W.copy:Click()
    Lab.Check("interact", "quick report prepared", true, W.edit:GetText():find("TWICHUI MAP", 1, true) ~= nil)
    Lab.Check("geometry", "report top aligned with viewport", true,
        math.abs(W.edit:GetTop() - W.edit:GetParent():GetTop()) < 2)
    Lab.Check("geometry", "report left aligned", "LEFT", W.edit:GetJustifyH())
    local before = W.edit:GetText()
    W.select:Click()
    Lab.Check("state", "reselection preserves prepared report", true, before == W.edit:GetText())
end)
Lab.Step("record mark stop", function()
    W.start:Click()
    Lab.Check("interact", "recording started", true, MC.Status().recording)
    Lab.Check("state", "event tap installed", "function", type(R.MapTrace))
    Lab.Settle(0.2)
    R.MapTrace("wheel", 1, 20, 24, 48)
    W.mark:Click()
    R.MapTrace("texture-failure", 900001, "synthetic injected failure")
    W.stop:Click()
    Lab.Check("interact", "recording stopped", false, MC.Status().recording)
    Lab.Check("state", "event tap released", nil, R.MapTrace)
    Lab.Check("interact", "finding included", true, W.edit:GetText():find("texture%-load%-failure") ~= nil)
    W.detailed:Click()
    Lab.Check("interact", "structured report prepared", true, W.edit:GetText():find('"schema":1', 1, true) ~= nil)
    local text = W.edit:GetText()
    W.prev:Click()
    Lab.Check("interact", "first chunk clamps previous", true, text == W.edit:GetText())
    W.next:Click(); W.prev:Click()
    Lab.Check("interact", "chunk round trip preserves text", true, text == W.edit:GetText())
    W.frame:Hide()
    Lab.Check("state", "closed window has no updater", nil, W.frame:GetScript("OnUpdate"))
    DX.OpenMap()
    Lab.Check("state", "window reused", W.frame, TwichUIMapDiagnostics)
    W.copy:Click()
end)
Lab.Finish()

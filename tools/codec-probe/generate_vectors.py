#!/usr/bin/env python3
"""Reproducible PUBLIC SYNTHETIC codec fixtures; no Market/service dependency."""
import base64
import hashlib
import json
from pathlib import Path
import random
import zlib

ROOT = Path(__file__).resolve().parent
ADDON = ROOT / 'TwichUI_CodecProbe'
MAX_OUTPUT = 512 * 1024


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def history(size):
    rng = random.Random(20261123)
    rows, length = [], 2
    for item in range(10000, 20000):
        price = 1000 + item * 13
        points = [[0, str(price + rng.randrange(-price // 3, price // 3)),
                   str(price + rng.randrange(-price // 4, price // 4)), rng.randrange(1, 5000)]
                  for _ in range(60)]
        row = [item, sha(str(item).encode()), 0, str(price), str(price), str(price),
               42, 0, 0, str(price), 14, 60, 60, points]
        encoded = json.dumps(row, separators=(',', ':')).encode()
        if length + len(encoded) + bool(rows) > size:
            break
        rows.append(encoded)
        length += len(encoded) + (len(rows) > 1)
    raw = b'[' + b','.join(rows) + b']'
    # Trailing JSON whitespace gives exact, safely bounded byte counts.
    raw += b' ' * (size - len(raw))
    assert len(raw) == size and json.loads(raw)
    return raw


def current():
    # Fixed-width/proof-like bytes; NOT an authenticated Market generation.
    rows = []
    for i in range(513):
        row = f'{10000+i:08x}' + sha(str(i).encode()) + '0' + f'{100000+i:010x}' * 3
        row += f'{42:014x}' + '0' + '0' + f'{100000+i:010x}' + '0e3c3c'
        assert len(row) == 135
        rows.append(row)
    return (''.join(rows) + ''.join(sha(f'proof:{i}'.encode()) for i in range(2047))).encode()


def fixtures():
    return [('small', b'market partition compression interoperability ' * 100),
            ('current', current()), ('history336', history(336400)),
            ('history512', history(MAX_OUTPUT))]


def binary(raw):
    return '"' + ''.join(f'\\{v:03d}' for v in raw) + '"'


def make(destination=None):
    destination = Path(destination) if destination else ADDON
    destination.mkdir(exist_ok=True, parents=True)
    lines = ['-- Generated public synthetic fixtures. See generate_vectors.py.',
             'local _, P = ...', 'P.Payloads = {}']
    manifest = {'synthetic': True, 'private_market_data': False, 'max_output_bytes': MAX_OUTPUT,
                'generator': 'Python stdlib zlib level6; raw RFC1951 and zlib RFC1950',
                'zlib_runtime': zlib.ZLIB_RUNTIME_VERSION, 'fixtures': []}
    for name, raw in fixtures():
        wrapped = zlib.compress(raw, 6)
        packed = {'raw': wrapped[2:-4], 'zlib': wrapped}
        assert 0 < len(raw) <= MAX_OUTPUT
        row = {'name': name, 'expected_bytes': len(raw), 'sha256': sha(raw), 'encodings': {}}
        lines += [f'P.Payloads.{name} = {{ expected = [=[{raw.decode()}]=], sha256 = "{sha(raw)}",']
        for mode, compressed in packed.items():
            assert zlib.decompress(compressed, -15 if mode == 'raw' else 15) == raw
            encoded = base64.b64encode(compressed).decode()
            if mode == 'raw' or name == 'small':
                lines.append(f'  {mode} = [=[{encoded}]=],')
            row['encodings'][mode] = {'input_bytes': len(compressed), 'base64_bytes': len(encoded), 'sha256': sha(compressed)}
        if name == 'small':
            lines += [f'  rawBytes = {binary(packed["raw"])},', f'  zlibBytes = {binary(packed["zlib"])},']
        else:
            # Exact externally generated bytes, NOT an encoder/checksum in Lua.
            lines += [f'  zlibPrefix = {binary(wrapped[:2])},', f'  zlibSuffix = {binary(wrapped[-4:])},']
        lines += ['}']
        manifest['fixtures'].append(row)
    (destination / 'Vectors.lua').write_text('\n'.join(lines) + '\n')
    return manifest


if __name__ == '__main__':
    manifest = make()
    (ROOT / 'vectors.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({'fixture_source_bytes': (ADDON / 'Vectors.lua').stat().st_size,
                      'expected_total_bytes': sum(x['expected_bytes'] for x in manifest['fixtures'])}))
